def generate_markdown_report(
    df: pd.DataFrame,
    report_title: str,
    author: str,
    include_sections: Dict[str, bool],
    notes: str = ""
) -> str:
    """Generates a comprehensive executive Markdown report."""
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
    total_postings = len(df)
    avg_lpa = df["salary_lpa"].mean() if total_postings > 0 else 0.0
    median_lpa = df["salary_lpa"].median() if total_postings > 0 else 0.0
    spam_count = int(df["is_spam"].sum()) if total_postings > 0 else 0
    spam_pct = (spam_count / total_postings * 100) if total_postings > 0 else 0.0

    all_exploded_skills = [s for sublist in df["skills"] for s in sublist] if total_postings > 0 else []
    skills_series = pd.Series(all_exploded_skills)
    top_skill = skills_series.mode()[0] if not skills_series.empty else "N/A"

    lines = []
    lines.append(f"# {report_title}")
    lines.append(f"**Generated By:** {author}  ")
    lines.append(f"**Timestamp:** {now_str}  ")
    lines.append(f"**Big Data Architecture:** Apache Spark (Batch), HDFS, Kafka Stream, Bloom Filter (Spam Defense), DGIM Stream Window, Spark MLlib, MongoDB  ")
    lines.append(f"**Dataset Scope:** {total_postings:,} Active Requisitions across Indian Tech Hubs  ")
    lines.append("")

    if notes.strip():
        lines.append("### 📝 Executive Memo")
        lines.append(f"> {notes.strip()}")
        lines.append("")

    if include_sections.get("kpis", True):
        lines.append("---")
        lines.append("## 1. Executive Summary & Key Hiring Metrics")
        lines.append(f"- **Total Requisitions Ingested & Analyzed:** {total_postings:,}")
        lines.append(f"- **Top In-Demand Competency:** {top_skill}")
        lines.append(f"- **Mean Indian Market Compensation:** {CURRENCY_SYMBOL}{avg_lpa:.2f} {CURRENCY_UNIT}")
        lines.append(f"- **Median Indian Market Compensation:** {CURRENCY_SYMBOL}{median_lpa:.2f} {CURRENCY_UNIT}")
        lines.append(f"- **Fraudulent Consultancy Intercept Rate:** {spam_pct:.1f}% ({spam_count:,} scam postings intercepted via Bloom Filter)")
        lines.append("")

    if include_sections.get("regional", True) and not df.empty:
        lines.append("---")
        lines.append("## 2. Regional Tech Hub Benchmarks (CTC in ₹ LPA)")
        lines.append("| Tech Hub / City | Total Requisitions | Mean CTC (₹ LPA) | Median CTC (₹ LPA) | Min CTC | Max CTC |")
        lines.append("| :--- | :--- | :--- | :--- | :--- | :--- |")
        city_grp = df.groupby("city").agg(
            count=("job_id", "count"),
            mean_ctc=("salary_lpa", "mean"),
            med_ctc=("salary_lpa", "median"),
            min_ctc=("salary_lpa", "min"),
            max_ctc=("salary_lpa", "max"),
        ).sort_values(by="count", ascending=False)

        for city, row in city_grp.iterrows():
            lines.append(
                f"| {city} | {int(row['count']):,} | {CURRENCY_SYMBOL}{row['mean_ctc']:.2f} | "
                f"{CURRENCY_SYMBOL}{row['med_ctc']:.2f} | {CURRENCY_SYMBOL}{row['min_ctc']:.1f} | {CURRENCY_SYMBOL}{row['max_ctc']:.1f} |"
            )
        lines.append("")

    if include_sections.get("skills", True) and not skills_series.empty:
        lines.append("---")
        lines.append("## 3. High-Velocity Technology Skills Ranking")
        lines.append("| Rank | Skill Name | Occurrences in Requisitions | Market Penetration (%) |")
        lines.append("| :--- | :--- | :--- | :--- |")
        top_skills_df = skills_series.value_counts().head(15).reset_index()
        top_skills_df.columns = ["skill", "count"]
        for idx, row in top_skills_df.iterrows():
            pct = (row["count"] / total_postings * 100) if total_postings > 0 else 0
            lines.append(f"| #{idx+1} | {row['skill']} | {int(row['count']):,} | {pct:.1f}% |")
        lines.append("")

    if include_sections.get("roles", True) and not df.empty:
        lines.append("---")
        lines.append("## 4. Engineering Role & Experience Tier Distribution")
        lines.append("### Compensation by Experience Tier:")
        exp_grp = df.groupby("experience_level").agg(
            count=("job_id", "count"),
            mean_ctc=("salary_lpa", "mean")
        ).reset_index()
        for _, row in exp_grp.iterrows():
            lines.append(f"- **{row['experience_level']}:** Mean {CURRENCY_SYMBOL}{row['mean_ctc']:.2f} {CURRENCY_UNIT} ({int(row['count']):,} positions)")
        lines.append("")

    if include_sections.get("algorithms", True):
        lines.append("---")
        lines.append("## 5. Big Data Algorithmic Defense & Stream Window Audit")
        lines.append("- **Bloom Filter Defense Layer:** Bit array capacity `m=50,000`, `k=5` Murmur3/SHA256 hashes. Successfully flagged and isolated fake consultancy spam strings before aggregation.")
        lines.append("- **DGIM Real-Time Stream Counting:** $O(\\log^2 N)$ memory sliding window over the continuous job ingest stream, capturing real-time spikes in GenAI, Kubernetes, and PySpark requirements with $< 50\\%$ bounded error.")
        lines.append("- **Spark MLlib Classifier Pipeline:** `StringIndexer` + `OneHotEncoderEstimator` + `VectorAssembler` + `RandomForestClassifier` (100 trees, depth 8) predicting Indian CTC brackets (< ₹6 LPA, ₹6 - ₹18 LPA, > ₹18 LPA).")
        lines.append("")

    lines.append("---")
    lines.append("*Report generated by Indian Job Market Trends & Hiring Intelligence System (Streamlit + Big Data Architecture).*")
    return "\n".join(lines)


